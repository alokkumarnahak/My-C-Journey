//preprocessor directive 
#include<stdio.h>

//main function 
int main() {

	//Demonstration of data types & variables in C
	int age = 25;
	float height = 5.9f;
	double weight = 70.5;
	char grade = 'A';


	printf("Age: %d\n", age);
	printf("Height: %f\n", height);
	printf("Weight: %lf\n", weight);
	printf("Grade: %c\n", grade);

	//return statement 
	return 0 ;
}